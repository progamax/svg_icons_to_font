import 'config.dart';
import 'otf_writer.dart';

/// Generates the Flutter `.dart` file mapping icon names to `IconData`.
class DartClassGenerator {
  /// Generates the Dart source code for the given [glyphs] and [config].
  static String generate({
    required List<IconGlyph> glyphs,
    required FontGeneratorConfig config,
  }) {
    final buffer = StringBuffer()
      ..writeln('// GENERATED CODE - DO NOT MODIFY BY HAND')
      ..writeln('// Generated by svg_icons_to_font')
      ..writeln()
      ..writeln("import 'package:flutter/widgets.dart';")
      ..writeln()
      ..writeln('/// Icons generated from SVG files for the [${config.fontFamily}] font.')
      ..writeln('abstract final class ${config.className} {')
      ..writeln('  ${config.className}._();')
      ..writeln()
      ..writeln("  static const String fontFamily = '${config.fontFamily}';");

    if (config.fontPackage != null && config.fontPackage!.isNotEmpty) {
      buffer.writeln("  static const String fontPackage = '${config.fontPackage}';");
    }

    buffer.writeln();

    final usedIdentifiers = <String>{'fontFamily', 'fontPackage', 'values'};
    final identifierEntries = <MapEntry<String, IconGlyph>>[];

    for (final glyph in glyphs) {
      var identifier = toDartIdentifier(glyph.name);
      if (usedIdentifiers.contains(identifier)) {
        var suffix = 2;
        while (usedIdentifiers.contains('$identifier$suffix')) {
          suffix++;
        }
        identifier = '$identifier$suffix';
      }
      usedIdentifiers.add(identifier);
      identifierEntries.add(MapEntry(identifier, glyph));
    }

    for (final entry in identifierEntries) {
      final id = entry.key;
      final glyph = entry.value;
      final hex = '0x${glyph.codePoint.toRadixString(16).toUpperCase()}';
      buffer.writeln('  /// Icon `${glyph.name}` ($hex).');
      if (config.fontPackage != null && config.fontPackage!.isNotEmpty) {
        buffer.writeln(
          '  static const IconData $id = IconData($hex, fontFamily: fontFamily, fontPackage: fontPackage);',
        );
      } else {
        buffer.writeln(
          '  static const IconData $id = IconData($hex, fontFamily: fontFamily);',
        );
      }
      buffer.writeln();
    }

    buffer.writeln('  /// Map of all generated icons by their identifier name.');
    buffer.writeln('  static const Map<String, IconData> values = <String, IconData>{');
    for (final entry in identifierEntries) {
      buffer.writeln("    '${entry.key}': ${entry.key},");
    }
    buffer
      ..writeln('  };')
      ..writeln('}');

    return buffer.toString();
  }

  /// Converts an arbitrary file stem into a valid lowerCamelCase Dart identifier.
  static String toDartIdentifier(String rawName) {
    final sanitized = rawName
        .replaceAll(RegExp(r'[^a-zA-Z0-9]+'), ' ')
        .trim();
    if (sanitized.isEmpty) return 'icon';

    final parts = sanitized.split(RegExp(r'\s+'));
    final first = parts.first.toLowerCase();
    final rest = parts.skip(1).map((p) {
      if (p.isEmpty) return '';
      return p[0].toUpperCase() + p.substring(1).toLowerCase();
    }).join();

    var candidate = '$first$rest';
    if (RegExp(r'^[0-9]').hasMatch(candidate)) {
      candidate = 'icon${candidate[0].toUpperCase()}${candidate.substring(1)}';
    }
    if (_dartReservedWords.contains(candidate)) {
      candidate = '${candidate}Icon';
    }
    return candidate;
  }

  static const Set<String> _dartReservedWords = {
    'assert',
    'break',
    'case',
    'catch',
    'class',
    'const',
    'continue',
    'default',
    'do',
    'else',
    'enum',
    'extends',
    'false',
    'final',
    'finally',
    'for',
    'if',
    'in',
    'is',
    'new',
    'null',
    'rethrow',
    'return',
    'super',
    'switch',
    'this',
    'throw',
    'true',
    'try',
    'var',
    'void',
    'while',
    'with',
  };
}
